export async function injectToolPageTranslations() {
  for (const [locale, data] of Object.entries(TRANSLATIONS)) {
    const commonPath = path.join(root, 'src/locales', locale, 'common.json');
    const common = JSON.parse(await readFile(commonPath, 'utf8'));
    common.toolPage = data.toolPage;
    common.toolForm = data.toolForm;
    await writeFile(commonPath, `${JSON.stringify(common, null, 2)}\n`, 'utf8');
    console.log(`Injected toolPage & toolForm translations for ${locale}`);
  }
}

if (process.argv[1]?.endsWith('inject-tool-page-translations.mjs')) {
  await injectToolPageTranslations();
}
